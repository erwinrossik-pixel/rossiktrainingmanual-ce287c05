export const HOMEWORK_DICTIONARIES: Record<Language, Dict> = { ro, de, en };

export function formatHomeworkText(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match,
  );
}

export function homeworkText(language: Language, key: string, params?: Record<string, string | number>): string {
  const template = HOMEWORK_DICTIONARIES[language][key] ?? HOMEWORK_DICTIONARIES.ro[key] ?? key;
  return formatHomeworkText(template, params);
}

const LOCALES: Record<Language, string> = { ro: "ro-RO", de: "de-DE", en: "en-GB" };

export function useHomeworkT() {
  const { language } = useLanguage();
  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => homeworkText(language, key, params),
    [language],
  );
  const formatDate = useCallback(
    (iso: string, withTime = true) =>
      new Date(iso).toLocaleString(LOCALES[language], {
        day: "2-digit",
        month: "2-digit",
        year: "numeric",
        ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
      }),
    [language],
  );
  const formatTime = useCallback(
    (date: Date) => date.toLocaleTimeString(LOCALES[language], { hour: "2-digit", minute: "2-digit" }),
    [language],
  );
  return { t, language, formatDate, formatTime };
}
